public class Printer {
    public void print(String texto){
        System.out.println("\nSe imprimió un texto: " + texto);
    }

    public void print(int Entero){
        System.out.println("\nSe imprimió un Entero: " + Entero);
    }

    public void print(double Decimal){
        System.out.println("\nSe imprimió un Decimal: " + Decimal);
    }

    public void print(boolean Booleano){
        System.out.println("\nSe imprimió un Booleano: " + Booleano);
    }
}
